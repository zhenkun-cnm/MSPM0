/* ================================================================
 *  DevTFT 接口函数实现
 * ================================================================ */

/**
 * @brief TFT 初始化：GPIO 配置 → 硬件复位 → SPI1 初始化 → 初始化序列
 */
static void tft_init(DevTFT *self)
{
    (void)self;

    /* 1. 初始化 GPIO 并纠正电平 */
    tft_gpio_init();

    /* 2. 硬件复位 */
    tft_hardware_reset();

    /* 3. 初始化 SPI1（与 W25Q128 共用，SysConfig 已配置） */
    SYSCFG_DL_W25Q64_init();

    /* 4. 发送初始化序列 */
    tft_init_sequence();

    /* 5. 清屏为黑色 */
    tft_fillScreen(self, TFT_BLACK);

    /* 6. 初始化光标 */
    g_cursorX = 0;
    g_cursorY = 0;
}

/**
 * @brief 填充整个屏幕为指定颜色
 */
static void tft_fillScreen(DevTFT *self, uint16_t color)
{
    uint16_t x, y;

    (void)self;

    tft_set_window(0, 0, TFT_WIDTH - 1, TFT_HEIGHT - 1);

    FLASH_CS_HIGH();
    TFT_DC_HIGH();
    TFT_CS_LOW();

    for (y = 0; y < TFT_HEIGHT; y++) {
        for (x = 0; x < TFT_WIDTH; x++) {
            spi_send_byte((uint8_t)(color >> 8));
            spi_send_byte((uint8_t)(color & 0xFF));
        }
    }

    TFT_CS_HIGH();
}

/**
 * @brief 画单个像素点
 */
static void tft_drawPixel(DevTFT *self, uint16_t x, uint16_t y, uint16_t color)
{
    (void)self;

    if (x >= TFT_WIDTH || y >= TFT_HEIGHT) return;

    tft_set_window(x, y, x, y);

    FLASH_CS_HIGH();
    TFT_DC_HIGH();
    TFT_CS_LOW();
    spi_send_byte((uint8_t)(color >> 8));
    spi_send_byte((uint8_t)(color & 0xFF));
    TFT_CS_HIGH();
}

/**
 * @brief 填充矩形区域
 */
static void tft_fillRect(DevTFT *self, uint16_t x, uint16_t y,
                         uint16_t w, uint16_t h, uint16_t color)
{
    uint16_t ex, ey;
    uint32_t pixelCount;

    (void)self;

    if (x >= TFT_WIDTH || y >= TFT_HEIGHT) return;

    ex = (x + w - 1 < TFT_WIDTH) ? (x + w - 1) : (TFT_WIDTH - 1);
    ey = (y + h - 1 < TFT_HEIGHT) ? (y + h - 1) : (TFT_HEIGHT - 1);

    pixelCount = (uint32_t)(ex - x + 1) * (ey - y + 1);

    tft_set_window(x, y, ex, ey);

    FLASH_CS_HIGH();
    TFT_DC_HIGH();
    TFT_CS_LOW();

    while (pixelCount--) {
        spi_send_byte((uint8_t)(color >> 8));
        spi_send_byte((uint8_t)(color & 0xFF));
    }

    TFT_CS_HIGH();
}

/**
 * @brief 在指定坐标画一个 ASCII 字符（8×16 字体）
 * @param x     起始 X 坐标
 * @param y     起始 Y 坐标
 * @param ch    ASCII 字符
 * @param color 前景色 (RGB565)
 * @param bg    背景色 (RGB565)
 */
static void tft_drawChar(DevTFT *self, uint16_t x, uint16_t y, char ch,
                         uint16_t color, uint16_t bg)
{
    uint8_t col, row;
    uint8_t idx;

    (void)self;

    if (ch < 0x20 || ch > 0x7E) ch = ' ';

    idx = (uint8_t)(ch - 0x20);

    for (row = 0; row < CHAR_HEIGHT; row++) {
        uint8_t line = font_8x16[idx][row];

        for (col = 0; col < CHAR_WIDTH; col++) {
            if (line & (0x80 >> col)) {
                tft_drawPixel(self, x + col, y + row, color);
            } else {
                tft_drawPixel(self, x + col, y + row, bg);
            }
        }
    }
}

/**
 * @brief 在指定坐标显示字符串（手动指定位置）
 */
static void tft_printString(DevTFT *self, uint16_t x, uint16_t y,
                            const char *str, uint16_t color, uint16_t bg)
{
    uint16_t cx = x;

    (void)self;

    if (str == NULL) return;

    while (*str) {
        if (*str == '\n') {
            cx = x;
            y += CHAR_HEIGHT;
        } else if (*str == '\r') {
            cx = x;
        } else {
            tft_drawChar(self, cx, y, *str, color, bg);
            cx += CHAR_WIDTH;
            if (cx + CHAR_WIDTH > TFT_WIDTH) {
                cx = 0;
                y += CHAR_HEIGHT;
            }
        }

        if (y + CHAR_HEIGHT > TFT_HEIGHT) {
            y = 0;              /* 溢出后滚回顶部 */
        }

        str++;
    }
}

/**
 * @brief printf 风格格式化输出到指定坐标
 * @note  内部用 vsnprintf 格式化到栈缓冲后调用 tft_printString
 */
static void tft_printf(DevTFT *self, uint16_t x, uint16_t y,
                       uint16_t color, uint16_t bg, const char *fmt, ...)
{
    char buf[48];
    va_list ap;

    if (fmt == NULL) return;

    va_start(ap, fmt);
    vsnprintf(buf, sizeof(buf), fmt, ap);
    va_end(ap);

    tft_printString(self, x, y, buf, color, bg);
}

/**
 * @brief 设置光标位置（用于流式 print 输出）
 */
static void tft_setCursor(DevTFT *self, uint16_t x, uint16_t y)
{
    (void)self;
    g_cursorX = x;
    g_cursorY = y;
}

/**
 * @brief 在光标位置流式输出字符串（自动换行/换行）
 */
static void tft_print(DevTFT *self, const char *str, uint16_t color, uint16_t bg)
{
    (void)self;

    if (str == NULL) return;

    while (*str) {
        if (*str == '\n') {
            g_cursorX = 0;
            g_cursorY += CHAR_HEIGHT;
        } else if (*str == '\r') {
            g_cursorX = 0;
        } else {
            tft_drawChar(self, g_cursorX, g_cursorY, *str, color, bg);
            g_cursorX += CHAR_WIDTH;
            if (g_cursorX + CHAR_WIDTH > TFT_WIDTH) {
                g_cursorX = 0;
                g_cursorY += CHAR_HEIGHT;
            }
        }

        if (g_cursorY + CHAR_HEIGHT > TFT_HEIGHT) {
            g_cursorY = 0;      /* 溢出后滚回顶部 */
        }

        str++;
    }
}

/* ================================================================
 *  注册 Device 接口
 * ================================================================ */

DevTFT* GetTFT(void)
{
    s_tftIf.init         = tft_init;
    s_tftIf.fillScreen   = tft_fillScreen;
    s_tftIf.drawPixel    = tft_drawPixel;
    s_tftIf.drawChar     = tft_drawChar;
    s_tftIf.printString  = tft_printString;
    s_tftIf.setCursor    = tft_setCursor;
    s_tftIf.print        = tft_print;
    s_tftIf.fillRect     = tft_fillRect;
    s_tftIf.printf       = tft_printf;

    return &s_tftIf;
}